"""The shape every incident follows, and how a case file is written out."""

from collections.abc import Callable
from dataclasses import dataclass

import duckdb

CONFIRMED = "confirmed"
REJECTED = "rejected"


@dataclass(frozen=True)
class Evidence:
    hypothesis: str
    check: str
    """What was measured, in one line."""
    finding: str
    verdict: str


@dataclass(frozen=True)
class Metric:
    name: str
    before: str
    after: str


@dataclass(frozen=True)
class CaseFile:
    number: int
    slug: str
    title: str
    symptom: str
    evidence: tuple[Evidence, ...]
    root_cause: str
    fix: str
    guard: str
    """The check left in place so it cannot happen silently again."""
    metrics: tuple[Metric, ...]


@dataclass(frozen=True)
class Incident:
    number: int
    slug: str
    title: str
    run: Callable[[duckdb.DuckDBPyConnection], CaseFile]


def verdict(confirmed: bool) -> str:
    return CONFIRMED if confirmed else REJECTED


ROUNDS_TO_ZERO = 0.0005


def pct(share: float) -> str:
    """0.153 -> '15.3%'. Tiny float leftovers print as 0.0%, never -0.0%."""
    return f"{0.0 if abs(share) < ROUNDS_TO_ZERO else share * 100:.1f}%"


def to_markdown(case: CaseFile) -> str:
    lines = [
        f"# Incident {case.number:02d}: {case.title}",
        "",
        "> Generated by `casebook run " + str(case.number) + "`. Every number below is computed from the data.",
        "",
        "## Symptom",
        "",
        case.symptom,
        "",
        "## Investigation",
        "",
        "| # | Hypothesis | Check | Finding | Verdict |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {i} | {e.hypothesis} | {e.check} | {e.finding} | **{e.verdict}** |"
        for i, e in enumerate(case.evidence, start=1)
    ]
    lines += ["", "## Root cause", "", case.root_cause, "", "## Fix", "", case.fix, "", "## Guard", "", case.guard]
    lines += ["", "## Before and after", "", "| Metric | Before | After |", "|---|---:|---:|"]
    lines += [f"| {m.name} | {m.before} | {m.after} |" for m in case.metrics]
    return "\n".join(lines) + "\n"
